/** Inclusive range of sprite indices to export. */
export interface SpriteRange {
  from: number
  to: number
}

export function fullRange(set: SpriteSet): SpriteRange {
  return { from: 0, to: set.sprites.length - 1 }
}

function spritesIn(set: SpriteSet, range: SpriteRange): Array<Sprite> {
  const { from, to } = range
  if (
    !Number.isInteger(from) ||
    !Number.isInteger(to) ||
    from < 0 ||
    to < from ||
    to >= set.sprites.length
  ) {
    throw new RangeError(
      `Sprite range ${from}-${to} outside 0-${set.sprites.length - 1}`,
    )
  }
  return set.sprites.slice(from, to + 1)
}

/**
 * SpritePad-style attribute byte (also used as byte 64 of a sprite block):
 * bits 0-3 colour, bit 4 overlay (next sprite is drawn over this one),
 * bit 5 expand X, bit 6 expand Y, bit 7 multicolour.
 */
export function spriteAttributeByte(
  sprite: Sprite,
  overlayIsNext = false,
): number {
  return (
    (sprite.color & 0x0f) |
    (overlayIsNext ? 0x10 : 0) |
    (sprite.expandX ? 0x20 : 0) |
    (sprite.expandY ? 0x40 : 0) |
    (sprite.mode === 'multicolor' ? 0x80 : 0)
  )
}

/** Does sprite i have the sprite right after it as its overlay? */
function overlaysNext(set: SpriteSet, i: number): boolean {
  const next = set.sprites.at(i + 1)
  return !!next && set.sprites[i].overlayId === next.id
}

export type PadByte = 'zero' | 'attributes'

/**
 * Raw sprite data, 64 bytes per sprite as it sits in memory: 63 bytes of
 * pixels plus a 64th byte that is 0 or the SpritePad attribute byte.
 */
export function exportSpritesBin(
  set: SpriteSet,
  range: SpriteRange = fullRange(set),
  pad: PadByte = 'zero',
): Uint8Array {
  const sprites = spritesIn(set, range)
  const out = new Uint8Array(sprites.length * SPRITE_STRIDE)
  sprites.forEach((sprite, i) => {
    out.set(sprite.data, i * SPRITE_STRIDE)
    if (pad === 'attributes') {
      out[i * SPRITE_STRIDE + SPRITE_BYTES] = spriteAttributeByte(
        sprite,
        overlaysNext(set, range.from + i),
      )
    }
  })
  return out
}

/** A KickAssembler-safe identifier from a display name. */
export function asmLabel(name: string, fallback = 'data'): string {
  const label = name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, '_')
    .replace(/^_+|_+$/g, '')
  return !label ? fallback : /^[0-9]/.test(label) ? `_${label}` : label
}

const hex = (n: number) => '$' + n.toString(16).padStart(2, '0')

/** A row of a sprite as text: hires '#'/'.', multicolour '1','2','3'/'.' doubled. */
function rowPicture(sprite: Sprite, pixels: Uint8Array, y: number): string {
  if (sprite.mode === 'hires') {
    return Array.from(pixels.slice(y * 24, y * 24 + 24), (p) =>
      p ? '#' : '.',
    ).join('')
  }
  return Array.from(pixels.slice(y * 12, y * 12 + 12), (p) =>
    (p ? String(p) : '.').repeat(2),
  ).join('')
}

/**
 * KickAssembler source: one label per sprite, 64 bytes each (63 data + pad),
 * with a picture of each row in the comments and the colours as constants.
 */
export function exportSpritesKickAss(
  set: SpriteSet,
  {
    range = fullRange(set),
    pad = 'zero',
    projectName = '',
  }: { range?: SpriteRange; pad?: PadByte; projectName?: string } = {},
): string {
  const sprites = spritesIn(set, range)
  const prefix = asmLabel(set.name, 'sprites')
  const lines: Array<string> = []
  const colour = (c: C64Color) => `${c} // ${COLOR_NAMES[c]}`
  lines.push(
    `// Sprite set "${set.name}"${projectName ? ` from project "${projectName}"` : ''}`,
    `// ${sprites.length} sprite(s), sprites ${range.from}-${range.to}, 64 bytes each (63 data + 1 ${pad === 'zero' ? 'zero pad' : 'attribute byte'}).`,
    '// Generated by C64-Pad. Place on a 64-byte boundary so sprite pointers = address / 64.',
    '',
    `.label ${prefix}_mc1 = ${colour(set.multicolor1)} ($d025)`,
    `.label ${prefix}_mc2 = ${colour(set.multicolor2)} ($d026)`,
  )
  sprites.forEach((sprite, i) => {
    lines.push(
      `.label ${prefix}_${range.from + i}_color = ${colour(sprite.color)} ($d027+n)`,
    )
  })
  lines.push('', '.align $40', `${prefix}:`)
  sprites.forEach((sprite, i) => {
    const index = range.from + i
    const pixels = readPixels(sprite.data, SPRITE_SHAPE, sprite.mode)
    lines.push(
      '',
      `// Sprite ${index} "${sprite.name}": ${sprite.mode === 'multicolor' ? 'multicolour' : 'hires'}${sprite.expandX ? ', expand X' : ''}${sprite.expandY ? ', expand Y' : ''}`,
      `${prefix}_${index}:`,
    )
    for (let y = 0; y < SPRITE_HEIGHT; y++) {
      const bytes = Array.from(sprite.data.slice(y * 3, y * 3 + 3), hex).join(
        ', ',
      )
      lines.push(`  .byte ${bytes}  // ${rowPicture(sprite, pixels, y)}`)
    }
    const last =
      pad === 'zero' ? 0 : spriteAttributeByte(sprite, overlaysNext(set, index))
    lines.push(
      `  .byte ${hex(last)}  // ${pad === 'zero' ? 'pad' : 'attributes'}`,
    )
  })
  lines.push('')
  return lines.join('\n')
}

export interface SpdResult {
  bytes: Uint8Array
  /** Things SPD V1 can't store, which were left out. */
  warnings: Array<string>
}

/**
 * SpritePad SPD V1 (SpritePad 2.0; read by all later SpritePad releases):
 * "SPD", version 1, sprites-1, animations-1, $d021, $d025, $d026, then 64
 * bytes per sprite (byte 64 = attributes), then four animation lists
 * (from frame, to frame, timer, attributes: bit 4 ping-pong, bit 7 enabled).
 */
export function exportSpritesSpd(
  set: SpriteSet,
  background: C64Color = 0,
): SpdResult {
  const warnings: Array<string> = []
  if (set.sprites.length > 256)
    throw new RangeError('SPD files hold at most 256 sprites')

  set.sprites.forEach((sprite, i) => {
    if (sprite.overlayId && !overlaysNext(set, i)) {
      warnings.push(
        `Sprite ${i} "${sprite.name}": SPD only stores an overlay on the very next sprite; this overlay was left out.`,
      )
    }
  })

  const animations: Array<{
    from: number
    to: number
    speed: number
    pingpong: boolean
  }> = []
  for (const anim of set.animations) {
    const indices = anim.frames.map((id) =>
      set.sprites.findIndex((s) => s.id === id),
    )
    const contiguous =
      indices.length > 0 &&
      indices.every((v, k) => v >= 0 && v === indices[0] + k)
    if (!contiguous) {
      warnings.push(
        `Animation "${anim.name}": SPD only stores a run of consecutive sprites (e.g. 4-7); it was left out.`,
      )
      continue
    }
    animations.push({
      from: indices[0],
      to: indices[indices.length - 1],
      speed: anim.speed,
      pingpong: anim.mode === 'pingpong',
    })
  }
  if (animations.length > 256)
    throw new RangeError('SPD files hold at most 256 animations')
  // The header stores count-1, so a file always has at least one animation;
  // with none to save, write a single disabled one.
  const enabled = animations.length > 0
  const anims = enabled
    ? animations
    : [{ from: 0, to: 0, speed: 1, pingpong: false }]

  const n = set.sprites.length
  const a = anims.length
  const bytes = new Uint8Array(9 + 64 * n + 4 * a)
  bytes.set([
    0x53,
    0x50,
    0x44,
    1,
    n - 1,
    a - 1,
    background,
    set.multicolor1,
    set.multicolor2,
  ])
  set.sprites.forEach((sprite, i) => {
    const at = 9 + i * 64
    bytes.set(sprite.data, at)
    bytes[at + 63] = spriteAttributeByte(sprite, overlaysNext(set, i))
  })
  const base = 9 + 64 * n
  anims.forEach((anim, k) => {
    bytes[base + k] = anim.from
    bytes[base + a + k] = anim.to
    bytes[base + 2 * a + k] = anim.speed
    bytes[base + 3 * a + k] = (anim.pingpong ? 0x10 : 0) | (enabled ? 0x80 : 0)
  })
  return { bytes, warnings }
}

/**
 * Sprites laid out in a grid as an indexed image (for PNG export). Each cell
 * is 24×21; expand flags are ignored. -1 = transparent.
 */
export function renderSpriteSheet(
  set: SpriteSet,
  {
    range = fullRange(set),
    columns = 8,
    gap = 0,
  }: { range?: SpriteRange; columns?: number; gap?: number } = {},
): IndexedImage {
  const sprites = spritesIn(set, range)
  const cols = Math.max(1, Math.min(columns, sprites.length))
  const rows = Math.ceil(sprites.length / cols)
  const width = cols * SPRITE_RENDER_WIDTH + (cols - 1) * gap
  const height = rows * SPRITE_HEIGHT + (rows - 1) * gap
  const pixels = new Int8Array(width * height).fill(-1)
  sprites.forEach((sprite, i) => {
    const img = renderSprite(set, sprite)
    const ox = (i % cols) * (SPRITE_RENDER_WIDTH + gap)
    const oy = Math.floor(i / cols) * (SPRITE_HEIGHT + gap)
    for (let y = 0; y < SPRITE_HEIGHT; y++) {
      for (let x = 0; x < SPRITE_RENDER_WIDTH; x++) {
        pixels[(oy + y) * width + ox + x] = img[y * SPRITE_RENDER_WIDTH + x]
      }
    }
  })
  return { width, height, pixels }
}
