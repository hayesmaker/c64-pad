#!/usr/bin/env bash
# Assemble the KickAssembler viewer stubs and embed them as TypeScript, so the
# app can build PRGs on the device without an assembler.
#   KICKASS=/path/to/KickAss.jar ./scripts/build-stubs.sh
set -euo pipefail
cd "$(dirname "$0")/.."
KICKASS="${KICKASS:-/opt/KickAss.jar}"
OUT=src/emulator/stubs
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"
for name in sprite-viewer charmap-viewer; do
  java -jar "$KICKASS" "stubs/$name.asm" -o "$TMP/$name.prg" -odir "$TMP" >/dev/null
  node -e '
    const fs = require("node:fs")
    const [prg, out, name] = process.argv.slice(1)
    const bytes = fs.readFileSync(prg)
    const ident = name.replace(/-(\w)/g, (_, c) => c.toUpperCase())
    fs.writeFileSync(out,
      `// Generated by scripts/build-stubs.sh from stubs/${name}.asm. Do not edit.\n` +
      `export const ${ident}Prg = ${JSON.stringify(bytes.toString("base64"))}\n`)
    console.log(`${name}: ${bytes.length} bytes`)
  ' "$TMP/$name.prg" "$OUT/$name.gen.ts" "$name"
done
